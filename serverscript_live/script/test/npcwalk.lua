npc_targets = {}      -- [nNpcIndex] = {index = 1, direction = 1}
npc_waypoints = {}    -- [nNpcIndex] = {waypoints, chat}

function GetNpcWaypoints(nNpcIndex)
	local nMapId = GetNpcWorldPos(nNpcIndex)
	local nNpcId = GetNpcParam(nNpcIndex, 1)

	for i = 1, getn(tbAmbienceNpc) do
		local tb = tbAmbienceNpc[i]
		if tb.nNpcId == nNpcId and tb.nMapId == nMapId then
			return tb.tbPos, tb.szChat
		end
	end
	return nil, nil
end

function IsArriveAt(nNpcIndex, nX, nY)
	local nX32, nY32 = GetNpcPos(nNpcIndex)
	return (abs(nX / 32 - nX32 / 32) < MAX_DIS and abs(nY / 32 - nY32 / 32) < MAX_DIS) and 1 or 0
end

function Walk(nNpcIndex)
	local ntilechat = random(1, 10)
	local ntilehieuung = random(1, 2)
	local msg = chat[random(1, 15)]
	local data = npc_waypoints[nNpcIndex]
	if not data then
		local waypoints, szChat = GetNpcWaypoints(nNpcIndex)
		if not waypoints then return end
		data = { waypoints = waypoints, chat = szChat }
		npc_waypoints[nNpcIndex] = data
	end

	local state = npc_targets[nNpcIndex]
	if not state then
		state = { index = 1, direction = 1 } -- direction 1 = ti?n, -1 = lùi
		npc_targets[nNpcIndex] = state
	end

	local wp = data.waypoints[state.index]
	if not wp then return end
	local nTX, nTY = wp[1] * 32, wp[2] * 32

	if IsArriveAt(nNpcIndex, nTX, nTY) == 1 then
		state.index = state.index + state.direction

		
		if state.index > getn(data.waypoints) then
			state.index = getn(data.waypoints) - 1
			state.direction = -1
		elseif state.index < 1 then
			state.index = 2
			state.direction = 1
		end
		wp = data.waypoints[state.index]
		nTX, nTY = wp[1] * 32, wp[2] * 32
	end
	if ntilechat == 2 then -- 
		NpcChat(nNpcIndex, "(sl)<color=Green>"..msg.."<color>")
		CastNpcSkill(nNpcIndex,1177,1)
	end
	NpcWalk(nNpcIndex, nTX, nTY)
end

function OnTimer(nNpcIndex, nTimeOut)
	Walk(nNpcIndex)
	
	SetNpcTimer(nNpcIndex, 18 * timer_sec)
end

function OnRevive(nNpcIndex, nTimeOut)
	npc_targets[nNpcIndex] = nil
	npc_waypoints[nNpcIndex] = nil
	Walk(nNpcIndex)
	SetNpcTimer(nNpcIndex, 18 * timer_sec)
end



